const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('gameRoulette', {
  getSnapshot: () => ipcRenderer.invoke('app:snapshot'),
  onChanged: (callback) => {
    const listener = (_event, value) => callback(value);
    ipcRenderer.on('app:changed', listener);
    return () => ipcRenderer.removeListener('app:changed', listener);
  },
  minimize: () => ipcRenderer.send('window:minimize'),
  toggleMaximize: () => ipcRenderer.send('window:toggle-maximize'),
  setBigPictureMode: (active) => ipcRenderer.invoke('window:big-picture', Boolean(active)),
  close: () => ipcRenderer.send('window:close'),
  chooseFolder: () => ipcRenderer.invoke('library:choose-folder'),
  chooseCoverFolder: () => ipcRenderer.invoke('library:choose-cover-folder'),
  choosePcsx2Cache: () => ipcRenderer.invoke('library:choose-pcsx2-cache'),
  autoPcsx2Cache: () => ipcRenderer.invoke('library:auto-pcsx2-cache'),
  setRomFolderEmulator: (folder, emulatorId) => ipcRenderer.invoke('library:set-folder-emulator', folder, emulatorId),
  setupEmulatorPreset: (emulatorId) => ipcRenderer.invoke('emulator:setup-preset', emulatorId),
  chooseEmulatorExecutable: () => ipcRenderer.invoke('emulator:choose-executable'),
  addCustomEmulator: (profile) => ipcRenderer.invoke('emulator:add-custom', profile),
  removeEmulator: (emulatorId) => ipcRenderer.invoke('emulator:remove', emulatorId),
  scanFolders: () => ipcRenderer.invoke('library:scan'),
  downloadCovers: () => ipcRenderer.invoke('library:download-covers'),
  importLaunchers: (sources) => ipcRenderer.invoke('library:import-launchers', sources),
  connectSteam: () => ipcRenderer.invoke('accounts:steam-connect'),
  saveSteamApiKey: (value) => ipcRenderer.invoke('accounts:steam-save-key', value),
  syncSteamLibrary: () => ipcRenderer.invoke('accounts:steam-sync'),
  getSteamAchievements: (gameKey) => ipcRenderer.invoke('achievements:steam-game', gameKey),
  disconnectSteam: () => ipcRenderer.invoke('accounts:steam-disconnect'),
  openSteamApiKeyPage: () => ipcRenderer.invoke('accounts:steam-open-key-page'),
  launchGame: (key) => ipcRenderer.invoke('library:launch', key),
  updateGame: (key, patch) => ipcRenderer.invoke('library:update-game', key, patch),
  removeGame: (key) => ipcRenderer.invoke('library:remove-game', key),
  clearRomGames: () => ipcRenderer.invoke('library:clear-roms'),
  spin: (filters) => ipcRenderer.invoke('roulette:spin', filters),
  chooseAvatar: () => ipcRenderer.invoke('profile:choose-avatar'),
  saveProfile: (name) => ipcRenderer.invoke('profile:save-name', name),
  setTheme: (name) => ipcRenderer.invoke('appearance:set-theme', name),
  saveCustomTheme: (theme) => ipcRenderer.invoke('appearance:save-custom-theme', theme),
  deleteCustomTheme: () => ipcRenderer.invoke('appearance:delete-custom-theme'),
  exportTheme: (name) => ipcRenderer.invoke('appearance:export-theme', name),
  importTheme: () => ipcRenderer.invoke('appearance:import-theme'),
  updateAppearance: (patch) => ipcRenderer.invoke('appearance:update', patch),
  chooseWallpaper: () => ipcRenderer.invoke('appearance:choose-wallpaper'),
  importBackup: () => ipcRenderer.invoke('backup:import'),
  exportBackup: () => ipcRenderer.invoke('backup:export'),
  connectRetroAchievements: (details) => ipcRenderer.invoke('ra:connect', details),
  refreshRetroAchievements: () => ipcRenderer.invoke('ra:refresh'),
  getAchievementSet: (gameId) => ipcRenderer.invoke('ra:game-set', gameId),
  linkAchievementGame: (key, gameId) => ipcRenderer.invoke('ra:link-game', key, gameId),
  disconnectRetroAchievements: () => ipcRenderer.invoke('ra:disconnect'),
  getOverlayUrl: () => ipcRenderer.invoke('obs:url'),
  revealDataFolder: () => ipcRenderer.invoke('app:reveal-data-folder'),
});
